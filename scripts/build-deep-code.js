#!/usr/bin/env node
/*
 * Embeds the VERIFIED example files (examples/<topic>/{python,typescript}) into js/deep/<topic>.code.js
 * so the code shown on the site is exactly the code the tests ran.
 *   usage: node scripts/build-deep-code.js
 */
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');

// topic -> use case -> { py: [files], ts: [files] }   (order = display order)
const MANIFEST = {
  signals: {
    cart: { py: ['cart.py'], ts: ['cart.ts', 'cart.activities.ts', 'cart.client.ts'] },
    approval: { py: ['approval.py'], ts: ['approval.ts', 'approval.activities.ts'] },
    entity: { py: ['entity.py'], ts: ['entity.ts', 'entity.activities.ts'] },
  },
  updates: {
    address: { py: ['address.py'], ts: ['address.ts'] },
    seats: { py: ['seats.py'], ts: ['seats.ts', 'seats.activities.ts'] },
    payment: { py: ['payment.py'], ts: ['payment.ts', 'payment.activities.ts', 'payment.client.ts'] },
  },
  queries: {
    tracking: { py: ['tracking.py'], ts: ['tracking.ts'] },
    progress: { py: ['progress.py'], ts: ['progress.ts', 'progress.activities.ts'] },
    diagnostics: { py: ['diagnostics.py'], ts: ['diagnostics.ts', 'diagnostics.activities.ts'] },
  },
  activities: {
    payments: { py: ['payments.py'], ts: ['payments.ts', 'payments.activities.ts'] },
    export: { py: ['export.py'], ts: ['export.ts', 'export.activities.ts'] },
    fanout: { py: ['fanout.py'], ts: ['fanout.ts', 'fanout.activities.ts', 'fanout.worker.ts'] },
  },
  workflows: {
    trial: { py: ['trial.py'], ts: ['trial.ts', 'trial.activities.ts'] },
    order: { py: ['order.py'], ts: ['order.v1.ts', 'order.v2.ts', 'order.v3.ts', 'order.activities.ts'] },
    import: { py: ['import_job.py'], ts: ['import.job.ts', 'import.job.activities.ts'] },
  },
  workers: {
    routing: { py: ['routing.py'], ts: ['routing.ts', 'routing.activities.ts', 'routing.host.ts'] },
    shutdown: { py: ['shutdown.py', 'crashing_worker.py'], ts: ['shutdown.ts', 'shutdown.activities.ts', 'crashing.worker.ts'] },
    tuning: { py: ['tuning.py'], ts: ['tuning.ts', 'tuning.activities.ts', 'tuning.worker.ts'] },
  },
  schedules: {
    report: { py: ['report.py'], ts: ['report.ts', 'report.schedule.ts'] },
    overlap: { py: ['overlap.py'], ts: ['overlap.ts', 'overlap.schedule.ts'] },
    sync: { py: ['sync.py'], ts: ['sync.ts', 'sync.activities.ts', 'sync.schedule.ts'] },
  },
};

const read = (topic, lang, file) => fs.readFileSync(path.join(root, 'examples', topic, lang, file), 'utf8').trimEnd();
const comment = (lang, file) => (lang === 'python' ? '# ===== ' : '// ===== ') + file + ' =====';

for (const [topic, cases] of Object.entries(MANIFEST)) {
  const out = {};
  for (const [name, files] of Object.entries(cases)) {
    out[name] = {};
    for (const [key, lang] of [['py', 'python'], ['ts', 'typescript']]) {
      const list = files[key];
      out[name][key] = list.map((f) => (list.length > 1 ? comment(lang, f) + '\n' : '') + read(topic, lang, f)).join('\n\n');
    }
  }
  const body = '// GENERATED by scripts/build-deep-code.js from examples/' + topic + '. Do not edit by hand.\n' +
    'DEEP_CODE.' + topic + ' = ' + JSON.stringify(out, null, 1) + ';\n';
  fs.writeFileSync(path.join(root, 'js', 'deep', topic + '.code.js'), body);
  console.log('wrote js/deep/' + topic + '.code.js');
}
